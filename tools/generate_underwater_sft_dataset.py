def quality_report(items):
    outputs = [item["output"] for item in items]
    questions = [item["instruction"] for item in items]
    lengths = [len(x) for x in outputs]
    categories = Counter()
    for f in FACTS:
        for item in items:
            if f["term"] in item["instruction"] or f["term"] in item["output"]:
                categories[f["category"]] += 1
                break
    return {
        "count": len(items),
        "unique_questions": len(set(questions)),
        "duplicate_outputs": len(outputs) - len(set(outputs)),
        "min_output_len": min(lengths),
        "max_output_len": max(lengths),
        "avg_output_len": round(sum(lengths) / len(lengths), 1),
        "short_lt70": sum(1 for x in lengths if x < 70),
        "long_gt220": sum(1 for x in lengths if x > 220),
        "bad_pattern_hits": sum(1 for item in items if any(bad in (item["instruction"] + item["output"]) for bad in BAD_PATTERNS)),
        "weak_anchor_hits": sum(1 for item in items if not any(anchor in (item["instruction"] + item["output"]) for anchor in DOMAIN_ANCHORS)),
    }


def main():
    if not DATA_PATH.exists():
        raise FileNotFoundError(DATA_PATH)
    if not BACKUP_PATH.exists():
        shutil.copy2(DATA_PATH, BACKUP_PATH)

    items = generate_from_facts()
    if len(items) != TARGET_COUNT:
        raise RuntimeError(f"Expected {TARGET_COUNT} items, got {len(items)}")

    report = quality_report(items)
    if report["unique_questions"] != TARGET_COUNT:
        raise RuntimeError("Duplicate questions detected")
    if report["bad_pattern_hits"] or report["weak_anchor_hits"] or report["short_lt70"] or report["long_gt220"]:
        raise RuntimeError(f"Quality gate failed: {report}")

    DATA_PATH.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print(f"Wrote {DATA_PATH}")
    print(f"Backup {BACKUP_PATH}")


if __name__ == "__main__":
    main()
