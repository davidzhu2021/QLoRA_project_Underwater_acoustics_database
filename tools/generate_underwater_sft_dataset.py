def normalize_item(item):
    return {
        "instruction": item["instruction"].strip(),
        "input": "",
        "output": item["output"].strip(),
    }


def is_valid(item):
    q = item["instruction"]
    a = item["output"]
    txt = q + a
    return (
        6 <= len(q) <= 80
        and 70 <= len(a) <= 220
        and any(anchor in txt for anchor in DOMAIN_ANCHORS)
        and not any(bad in txt for bad in BAD_PATTERNS)
    )


def add(items, seen_q, question, answer):
    item = normalize_item({"instruction": question, "output": answer})
    if item["instruction"] in seen_q:
        return
    if is_valid(item):
        items.append(item)
        seen_q.add(item["instruction"])


