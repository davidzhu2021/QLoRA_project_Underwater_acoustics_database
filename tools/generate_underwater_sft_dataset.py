def clean_application(text):
    cleaned = text.strip()
    replacements = (
        ("常用于", ""),
        ("可用于", ""),
        ("用于", ""),
        ("适合", ""),
        ("影响", ""),
        ("限制", ""),
        ("决定", ""),
        ("常与", "与"),
    )
    for prefix, replacement in replacements:
        if cleaned.startswith(prefix):
            cleaned = replacement + cleaned[len(prefix):]
            break
    return cleaned.strip(" ，。；;")


